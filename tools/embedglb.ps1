# Embeds a .glb model in a script, so the game can load it straight from the folder
# (a browser won't let a page opened from disk fetch a .glb file).
#   powershell -ExecutionPolicy Bypass -File tools\embedglb.ps1 <model.glb> models\miku.js MIKU_GLB
param([Parameter(Mandatory)] [string]$In, [Parameter(Mandatory)] [string]$Out, [string]$Var = 'MIKU_GLB')
$bytes = [IO.File]::ReadAllBytes((Resolve-Path $In))
$b64 = [Convert]::ToBase64String($bytes)
$name = [IO.Path]::GetFileName($In)
$text = "// Generated by tools/embedglb.ps1 from $name. Do not edit by hand.`nwindow.$Var = `"$b64`";`n"
[IO.File]::WriteAllText((Join-Path (Get-Location) $Out), $text, (New-Object Text.UTF8Encoding($false)))
"Embedded $name ({0:N1} MB) -> $Out" -f ($bytes.Length / 1MB)
